#!/usr/bin/env python3
"""SessionEnd (on /clear): write a handoff for the next session and commit it.

The handoff is built from facts only: the session's own prompts and last report from its
transcript, the commits and uncommitted changes since the session began, the gate's verdict,
and the task queue. Nothing is summarized by a model, so nothing is invented.

It commits only the handoff file. It pushes only on an agent branch (claude/*) that already
tracks a remote, so a laptop checkout is never pushed behind its owner's back.
"""
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2])
HANDOFFS = ROOT / ".claude" / "handoffs"
SESSIONS = ROOT / ".claude" / "state" / "sessions"
MAX_PROMPT, MAX_REPORT = 600, 3000


def run(*args, timeout=60):
    try:
        return subprocess.run(list(args), cwd=ROOT, capture_output=True, text=True, timeout=timeout).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return ""


def clip(s, n):
    s = s.strip()
    return s if len(s) <= n else s[:n].rstrip() + " […]"


def human_prompt(text):
    """A typed prompt, or a slash command rendered as `/name args`; None for harness-injected text."""
    name = re.search(r"<command-name>(.*?)</command-name>", text, re.S)
    if name:
        args = re.search(r"<command-args>(.*?)</command-args>", text, re.S)
        cmd = name.group(1).strip()
        return None if cmd in ("/clear",) else f"{cmd} {args.group(1).strip() if args else ''}".strip()
    if text.lstrip().startswith("<"):
        return None
    return text


def read_transcript(path):
    title, prompts, report = None, [], ""
    try:
        lines = Path(path).read_text(encoding="utf-8").splitlines()
    except (OSError, TypeError):
        return title, prompts, report
    for line in lines:
        try:
            e = json.loads(line)
        except ValueError:
            continue
        if e.get("type") == "ai-title":
            title = e.get("aiTitle") or title
        if e.get("isSidechain") or e.get("isMeta"):
            continue
        content = (e.get("message") or {}).get("content")
        if e.get("type") == "user" and isinstance(content, str):
            p = human_prompt(content)
            if p:
                prompts.append(p)
        elif e.get("type") == "assistant" and isinstance(content, list):
            text = "\n".join(b.get("text", "") for b in content if b.get("type") == "text").strip()
            if text:
                report = text
    return title, prompts, report


def tasks_summary():
    try:
        tasks = json.loads((ROOT / "program/data/tasks.json").read_text(encoding="utf-8"))["tasks"]
    except (OSError, ValueError, KeyError):
        return []
    active = [t for t in tasks if t["status"] in ("in_progress", "blocked")]
    queue = sorted((t for t in tasks if t["status"] == "open"), key=lambda t: t["priority"])[:5]
    return [f"- {t['id']} [{t['status']}] {t['title']}" + (f" ({t['log'][-1]})" if t.get("log") else "") for t in active] + \
           [f"- {t['id']} [open, p{t['priority']}] {t['title']}" for t in queue]


def main():
    event = json.load(sys.stdin)
    sid = event.get("session_id", "unknown")
    try:
        start = json.loads((SESSIONS / f"{sid}.json").read_text())
    except (OSError, ValueError):
        start = {}
    title, prompts, report = read_transcript(event.get("transcript_path"))
    if not prompts and not report:
        return
    base = start.get("head") or ""
    commits = run("git", "log", "--oneline", f"{base}..HEAD") if base else ""
    diffstat = run("git", "diff", "--shortstat", base, "HEAD") if base else ""
    status = run("git", "status", "--short")
    gate = run(sys.executable, "program/tools/validate.py").splitlines()
    now = datetime.now(timezone.utc)

    md = [f"# Handoff: {title or 'session ' + sid[:8]}", "",
          f"*Session `{sid}`, ended by `{event.get('reason', '?')}` at {now.isoformat(timespec='minutes')}. "
          f"Branch `{run('git', 'branch', '--show-current')}`. Generated by `.claude/hooks/handoff.py` from the transcript and git.*", "",
          "## What was asked", ""]
    md += [f"{i}. {clip(p, MAX_PROMPT)}" for i, p in enumerate(prompts, 1)] or ["(no typed prompts)"]
    md += ["", "## Commits this session", "", f"```\n{commits}\n```" if commits else "None.",
           *([f"", diffstat] if diffstat else []),
           "", "## Uncommitted at the end", "", f"```\n{status}\n```" if status else "Nothing: the tree was clean.",
           "", "## Gate", "", f"`validate.py`: {gate[-1] if gate else 'did not run'}",
           "", "## Task queue", "", *(tasks_summary() or ["(tasks.json unreadable)"]),
           "", "## Last report to the user", "", clip(report, MAX_REPORT) or "(none)", ""]

    HANDOFFS.mkdir(parents=True, exist_ok=True)
    out = HANDOFFS / f"{now.strftime('%Y%m%dT%H%MZ')}-{sid[:8]}.md"
    out.write_text("\n".join(md), encoding="utf-8")

    rel = out.relative_to(ROOT).as_posix()
    run("git", "add", "--", rel)
    run("git", "-c", "core.hooksPath=/dev/null", "commit", "--no-verify", "-q", "-m",
        f"Session handoff: {title or sid[:8]}", "--", rel)
    branch = run("git", "branch", "--show-current")
    if branch.startswith("claude/") and run("git", "rev-parse", "--abbrev-ref", "@{upstream}"):
        run("git", "push", "-q", timeout=45)


if __name__ == "__main__":
    main()
