#!/usr/bin/env python3
"""Build every generated view from program/data/*.json and program/ledger/.

Views (never edit them by hand):
    program/bibliography.md   annotated bibliography grouped by layer
    program/concept-map.md    Mermaid diagram per layer
    program/claims.md         claim index with derived tiers, and the check ledger
    program/phenomena.md      emergence scoreboard and phenomena menu

Usage:
    python3 program/tools/render.py           # write the views
    python3 program/tools/render.py --check   # exit 1 if any view on disk is out of date
"""
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check  # noqa: E402
import db  # noqa: E402
import phenomena  # noqa: E402

HEADER = "*Generated by `program/tools/render.py` from {src}. Edit the source, not this file.*"


def bibliography():
    bib, layers = db.load("bibliography"), db.load("concepts")["meta"]["layers"]
    by_layer = defaultdict(list)
    for e in bib["entries"]:
        by_layer[e["layers"][0] if e["layers"] else "L?"].append(e)
    legend = " · ".join(f"**{k}** ({v})" for k, v in bib["meta"]["status_legend"].items())
    out = ["# Annotated bibliography", "", HEADER.format(src="`data/bibliography.json`"), "", f"Status: {legend}.", ""]
    for layer in sorted(by_layer):
        out += [f"## {layer}. {layers.get(layer, '')}", ""]
        for e in sorted(by_layer[layer], key=lambda x: (x["year"], x["key"])):
            yr = f"{-e['year']} BCE" if e["year"] < 0 else str(e["year"])
            title = f"[{e['title']}]({e['url']})" if e.get("url") else e["title"]
            st = f"**{e['status']}**" if e["status"].startswith("checked") else f"*{e['status']}*"
            rel = [f"{r} " + ", ".join(e[r]) for r in ("supports", "challenges") if e.get(r)]
            out.append(f"- `{e['key']}` {e['authors']} ({yr}). {title}. *{e['venue']}*. [{st}]  ")
            out.append(f"  {e['annotation']}" + (f"  \n  _{'; '.join(rel)}._" if rel else ""))
        out.append("")
    return "\n".join(out)


def concept_map():
    concepts = db.load("concepts")
    layers = concepts["meta"]["layers"]
    node_layer = {n["id"]: n["layer"] for n in concepts["nodes"]}
    out = ["# Concept map", "", HEADER.format(src="`data/concepts.json`"), "",
           "Each diagram shows one layer's concepts and every edge touching them.", ""]
    for layer in sorted(layers):
        ids = {n["id"] for n in concepts["nodes"] if n["layer"] == layer}
        if not ids:
            continue
        es = [e for e in concepts["edges"] if e["source"] in ids or e["target"] in ids]
        out += [f"## {layer}. {layers[layer]}", "", "```mermaid", "graph LR"]
        shown = ids | {e["source"] for e in es} | {e["target"] for e in es}
        for x in sorted(shown):
            label = x if node_layer[x] == layer else f"{x} ({node_layer[x]})"
            out.append(f'  {x.replace("-", "_")}["{label}"]')
        for e in es:
            out.append(f'  {e["source"].replace("-", "_")} -- {e["relation"]} --> {e["target"].replace("-", "_")}')
        out += ["```", ""]
        for n in concepts["nodes"]:
            if n["layer"] == layer:
                f = f" `{n['formal']}`" if n.get("formal") else ""
                out.append(f"- **{n['id']}**: {n['definition']}{f}")
        out.append("")
    return "\n".join(out)


def claims():
    doc = db.load("claims")
    checks = check.load_checks()
    ledger = check.read_ledger()
    tiers = check.tiers(checks, ledger)
    esc = lambda s: str(s).replace("|", "\\|")  # noqa: E731
    out = ["# Claims and verification", "", HEADER.format(src="`data/claims.json`, `checks/` and `ledger/`"), "",
           "The tier is derived from the ledger by `tools/check.py` (`tiers`), never typed in. "
           "Method: [`harness.md` §5](harness.md).", "",
           "## Claim index", "", "| ID | Layer | Status | Tier | Title |", "|---|---|---|---|---|"]
    for c in doc["claims"]:
        out.append(f"| {c['id']} | {c['layer']} | {c['status']} | {tiers[c['id']][0]} | {esc(c['title'])} |")
    out += ["", "## Master relations", "", "| ID | Tier | Name | Condition |", "|---|---|---|---|"]
    for m in doc["master_relations"]:
        out.append(f"| {m['id']} | {tiers[m['id']][0]} | {esc(m['name'])} | {esc(m['condition'])} |")
    subjects = sorted({c.subject for c, _, _ in checks if c.subject})
    out += ["", "## Checked subjects", "",
            "A subject is a claim id, optionally narrowed to a clause (`.clause`) or a proposed restatement (`~variant`).", "",
            "| Subject | Tier | Why |", "|---|---|---|"]
    for s in subjects:
        out.append(f"| {s} | {tiers[s][0]} | {esc(tiers[s][1])} |")
    out += ["", "## Ledger", "", "| Check | Role | Tool | Expect | Result | State | Statement |", "|---|---|---|---|---|---|---|"]
    for c, src, d in checks:
        e = ledger.get(c.id)
        out.append(f"| `{c.id}` | {c.role} | {c.kind} | {c.expect} | {e['result'] if e else '—'} | "
                   f"{check.entry_state(c, d, e)} | {esc(c.statement)} |")
    return "\n".join(out) + "\n"


VIEWS = {
    "bibliography.md": bibliography,
    "concept-map.md": concept_map,
    "claims.md": claims,
    "phenomena.md": phenomena.render,
}


def build():
    return {db.PROGRAM / name: f() for name, f in VIEWS.items()}


def stale():
    return [p for p, text in build().items() if not p.exists() or p.read_text(encoding="utf-8") != text]


def main():
    if "--check" in sys.argv:
        bad = stale()
        for p in bad:
            print(f"out of date: {p.relative_to(db.REPO)} (run python3 program/tools/render.py)")
        sys.exit(1 if bad else 0)
    for p, text in build().items():
        p.write_text(text, encoding="utf-8")
    print("wrote " + ", ".join(VIEWS))


if __name__ == "__main__":
    main()
